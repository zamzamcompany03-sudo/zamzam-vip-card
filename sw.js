// Service Worker — بطاقة الثقة الذهبية VIP
// الهدف الوحيد لهذا الملف: ضمان إن أي تحديث نرفعه على التطبيق ينعكس
// تلقائياً حتى للأجهزة اللي أضافت التطبيق لشاشتها الرئيسية (Add to
// Home Screen) — هذي الأجهزة تفتح بوضع "مستقل" بدون زر تحديث ولا
// سحب-للتحديث، فبدون هذا الملف تضل عالقة على أول نسخة فتحتها للأبد.
//
// الإستراتيجية: "الشبكة أولاً" — كل فتح للتطبيق يحاول يجيب آخر نسخة
// من الخادم فوراً. يستخدم النسخة المحفوظة محلياً بس لو ما فيه إنترنت
// إطلاقاً، حتى يفتح التطبيق حتى بدون نت بدل ما ينكسر تمامًا.
// ============================================================

const CACHE_NAME = 'zamzam-vip-v1';

self.addEventListener('install', (event) => {
  // يفعّل النسخة الجديدة من هذا الملف فوراً، بدل ما ينتظر لحد ما
  // المستخدم يسكّر كل تبويبات/نُسخ التطبيق المفتوحة يدوياً
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    Promise.all([
      // يحذف أي كاش قديم من نسخ سابقة لهذا الملف نفسه (لو غيّرنا اسم
      // CACHE_NAME بتحديث مستقبلي)، حتى ما تتراكم نسخ قديمة بلا داعي
      caches.keys().then((keys) =>
        Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k)))
      ),
      // يتحكم فوراً بأي صفحة مفتوحة حالياً، بدل ما ينتظر إعادة تحميلها يدوياً
      self.clients.claim(),
    ])
  );
});

self.addEventListener('fetch', (event) => {
  event.respondWith(
    fetch(event.request)
      .then((response) => {
        // كل طلب ناجح من الشبكة، نحفظ نسخة طازجة منه بالكاش —
        // هذا يضمن إن الكاش نفسه دايماً محدَّث بآخر نسخة شغّالة
        const responseClone = response.clone();
        caches.open(CACHE_NAME).then((cache) => {
          cache.put(event.request, responseClone);
        });
        return response;
      })
      .catch(() =>
        // فشل الاتصال بالشبكة (غالباً بدون إنترنت) — نرجع للنسخة
        // المحفوظة محلياً بدل ما يفشل فتح التطبيق كلياً
        caches.match(event.request)
      )
  );
});
